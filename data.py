for _s in SCHOOLS:
    pool = (["کارگاه " + f for f in _s["fields"]] + ["ریاضی", "ادبیات فارسی", "زبان انگلیسی", "دین و زندگی", "فیزیک"]
            if _s["tech"] else SUBJ[_s["level"]])
    names = F_NAMES if _s["girl"] else M_NAMES
    _s["teachers"] = [dict(name=f"{r.choice(names)} {r.choice(FAMILIES)}", subject=sub, years=r.randrange(3, 28))
                      for sub in r.sample(pool, min(6, len(pool)))]
